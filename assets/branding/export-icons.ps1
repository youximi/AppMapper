# Regenerate the checked-in Android and Windows resources from the two source SVGs.
# Requires Windows PowerShell 5.1+ or PowerShell 7 on Windows; no additional packages.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName PresentationCore, WindowsBase

$repositoryRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$androidResources = Join-Path $repositoryRoot 'apps/android/app/src/main/res'
$windowsAssets = Join-Path $repositoryRoot 'apps/windows/controller/Assets'
$androidNamespace = 'http://schemas.android.com/apk/res/android'
$invariantCulture = [Globalization.CultureInfo]::InvariantCulture
$utf8 = [Text.UTF8Encoding]::new($false)
[xml]$mark = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'appmapper-mark.svg') -Raw
[xml]$icon = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'appmapper-icon.svg') -Raw

function Write-ResourceText([string]$path, [string]$content) {
    [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($path))
    [IO.File]::WriteAllText($path, $content + [Environment]::NewLine, $utf8)
}

function Get-ClipNode($node) {
    $id = $node.GetAttribute('clip-path').Replace('url(#', '').Replace(')', '')
    return $node.OwnerDocument.SelectSingleNode("//*[local-name()='clipPath' and @id='$id']/*[local-name()='path']")
}

function Get-Translation($node) {
    $match = [regex]::Match($node.GetAttribute('transform'), '^translate\((-?[\d.]+)[ ,]+(-?[\d.]+)\)$')
    if (-not $match.Success) { throw 'Only SVG translation transforms are supported by this exporter.' }
    return @([double]::Parse($match.Groups[1].Value, $invariantCulture), [double]::Parse($match.Groups[2].Value, $invariantCulture))
}

function Set-AndroidAttribute($node, [string]$name, [string]$value) {
    $attribute = $node.OwnerDocument.CreateAttribute('android', $name, $androidNamespace)
    $attribute.Value = $value
    [void]$node.Attributes.Append($attribute)
}

function Add-VectorNode($source, $parent, [string]$fill, [string]$overrideFill) {
    if ($source -isnot [Xml.XmlElement]) { return }
    $document = $parent.OwnerDocument
    if ($source.HasAttribute('fill')) { $fill = $source.GetAttribute('fill') }
    switch ($source.LocalName) {
        'g' {
            $group = $document.CreateElement('group')
            if ($source.HasAttribute('transform')) {
                $translation = Get-Translation $source
                Set-AndroidAttribute $group 'translateX' $translation[0].ToString($invariantCulture)
                Set-AndroidAttribute $group 'translateY' $translation[1].ToString($invariantCulture)
            }
            if ($source.HasAttribute('clip-path')) {
                $clipSource = Get-ClipNode $source
                $clip = $document.CreateElement('clip-path')
                # Compose's VectorGroup does not read clip-path fillType. Outline the even-odd
                # region so its hole has opposite winding and works with both renderers.
                $outline = [Windows.Media.Geometry]::Parse('F0 ' + $clipSource.GetAttribute('d')).GetOutlinedPathGeometry()
                $outline.FillRule = [Windows.Media.FillRule]::Nonzero
                $clipData = $outline.ToString($invariantCulture) -replace '^F1\s*', ''
                Set-AndroidAttribute $clip 'pathData' $clipData
                Set-AndroidAttribute $clip 'fillType' 'nonZero'
                [void]$group.AppendChild($clip)
            }
            foreach ($child in $source.ChildNodes) { Add-VectorNode $child $group $fill $overrideFill }
            [void]$parent.AppendChild($group)
        }
        { $_ -in 'path', 'circle' } {
            $path = $document.CreateElement('path')
            $color = if ($overrideFill) { $overrideFill } else { $fill }
            Set-AndroidAttribute $path 'fillColor' $color
            if ($source.LocalName -eq 'circle') {
                # The source icon's white circle has center (36,36) and radius 36.
                Set-AndroidAttribute $path 'pathData' 'M0,36 A36,36 0,1 0,72 36 A36,36 0,1 0,0 36 Z'
            } else {
                Set-AndroidAttribute $path 'pathData' $source.GetAttribute('d')
                if ($source.GetAttribute('fill-rule') -eq 'evenodd') {
                    Set-AndroidAttribute $path 'fillType' 'evenOdd'
                }
            }
            [void]$parent.AppendChild($path)
        }
    }
}

function Write-Vector($source, [string]$name, [int]$size, [int]$viewport, [double]$scale, [int]$inset, [string]$fill) {
    $document = [xml]::new()
    [void]$document.AppendChild($document.CreateXmlDeclaration('1.0', 'utf-8', $null))
    [void]$document.AppendChild($document.CreateComment(' Generated by assets/branding/export-icons.ps1. '))
    $vector = $document.CreateElement('vector')
    $vector.SetAttribute('xmlns:android', $androidNamespace)
    Set-AndroidAttribute $vector 'width' ($size.ToString() + 'dp')
    Set-AndroidAttribute $vector 'height' ($size.ToString() + 'dp')
    Set-AndroidAttribute $vector 'viewportWidth' $viewport.ToString()
    Set-AndroidAttribute $vector 'viewportHeight' $viewport.ToString()
    [void]$document.AppendChild($vector)
    $scaledGroup = $document.CreateElement('group')
    Set-AndroidAttribute $scaledGroup 'pivotX' ($viewport / 2).ToString($invariantCulture)
    Set-AndroidAttribute $scaledGroup 'pivotY' ($viewport / 2).ToString($invariantCulture)
    Set-AndroidAttribute $scaledGroup 'scaleX' $scale.ToString($invariantCulture)
    Set-AndroidAttribute $scaledGroup 'scaleY' $scale.ToString($invariantCulture)
    [void]$vector.AppendChild($scaledGroup)
    $content = $document.CreateElement('group')
    Set-AndroidAttribute $content 'translateX' $inset.ToString()
    Set-AndroidAttribute $content 'translateY' $inset.ToString()
    foreach ($child in $source.DocumentElement.ChildNodes) { Add-VectorNode $child $content '#000000' $fill }
    [void]$scaledGroup.AppendChild($content)
    $settings = [Xml.XmlWriterSettings]::new()
    $settings.Encoding = $utf8
    $settings.Indent = $true
    $path = Join-Path $androidResources ('drawable/' + $name + '.xml')
    [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($path))
    $writer = [Xml.XmlWriter]::Create($path, $settings)
    try { $document.Save($writer) } finally { $writer.Dispose() }
}

function Add-SvgDrawingNode($source, $parent, [string]$fill) {
    if ($source -isnot [Xml.XmlElement]) { return }
    if ($source.HasAttribute('fill')) { $fill = $source.GetAttribute('fill') }
    switch ($source.LocalName) {
        'g' {
            $group = [Windows.Media.DrawingGroup]::new()
            if ($source.HasAttribute('transform')) {
                $translation = Get-Translation $source
                $group.Transform = [Windows.Media.TranslateTransform]::new($translation[0], $translation[1])
            }
            if ($source.HasAttribute('clip-path')) {
                $clip = Get-ClipNode $source
                $group.ClipGeometry = [Windows.Media.Geometry]::Parse('F0 ' + $clip.GetAttribute('d'))
            }
            foreach ($child in $source.ChildNodes) { Add-SvgDrawingNode $child $group $fill }
            $parent.Children.Add($group)
        }
        { $_ -in 'path', 'circle' } {
            if ($source.LocalName -eq 'circle') {
                $center = [Windows.Point]::new(36, 36)
                $geometry = [Windows.Media.EllipseGeometry]::new($center, 36, 36)
            } else {
                $rule = if ($source.GetAttribute('fill-rule') -eq 'evenodd') { 'F0 ' } else { 'F1 ' }
                $geometry = [Windows.Media.Geometry]::Parse($rule + $source.GetAttribute('d'))
            }
            $brush = [Windows.Media.BrushConverter]::new().ConvertFromInvariantString($fill)
            $parent.Children.Add([Windows.Media.GeometryDrawing]::new($brush, $null, $geometry))
        }
    }
}

function Get-IconPng([int]$size) {
    $drawing = [Windows.Media.DrawingGroup]::new()
    foreach ($node in $icon.DocumentElement.ChildNodes) {
        if ($node.LocalName -eq 'g' -and $size -le 24) {
            # Slightly enlarge only the mark in small frames; the white circle stays unchanged.
            $smallMark = [Windows.Media.DrawingGroup]::new()
            $smallMark.Transform = [Windows.Media.ScaleTransform]::new(1.1, 1.1, 36, 36)
            Add-SvgDrawingNode $node $smallMark '#000000'
            $drawing.Children.Add($smallMark)
        } else {
            Add-SvgDrawingNode $node $drawing '#000000'
        }
    }
    $visual = [Windows.Media.DrawingVisual]::new()
    $context = $visual.RenderOpen()
    $context.PushTransform([Windows.Media.ScaleTransform]::new($size / 72, $size / 72))
    $context.PushClip([Windows.Media.RectangleGeometry]::new([Windows.Rect]::new(0, 0, 72, 72)))
    $context.DrawDrawing($drawing)
    $context.Close()
    $bitmap = [Windows.Media.Imaging.RenderTargetBitmap]::new($size, $size, 96, 96, [Windows.Media.PixelFormats]::Pbgra32)
    $bitmap.Render($visual)
    $encoder = [Windows.Media.Imaging.PngBitmapEncoder]::new()
    $encoder.Frames.Add([Windows.Media.Imaging.BitmapFrame]::Create($bitmap))
    $stream = [IO.MemoryStream]::new()
    try { $encoder.Save($stream); return ,$stream.ToArray() } finally { $stream.Dispose() }
}

Write-Vector $mark 'ic_launcher_foreground' 108 108 1.08 18 ''
Write-Vector $mark 'ic_launcher_monochrome' 108 108 1.08 18 '#FFFFFF'
Write-Vector $mark 'ic_notification' 24 72 1.2 0 '#FFFFFF'
Write-Vector $icon 'ic_appmapper' 48 72 1 0 ''
Write-ResourceText (Join-Path $androidResources 'values/icon_colors.xml') @'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets/branding/export-icons.ps1. -->
<resources>
    <color name="ic_launcher_background">#FFFFFF</color>
</resources>
'@
Write-ResourceText (Join-Path $androidResources 'mipmap-anydpi-v26/ic_launcher.xml') @'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets/branding/export-icons.ps1. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'@

[void][IO.Directory]::CreateDirectory($windowsAssets)
[IO.File]::WriteAllBytes((Join-Path $windowsAssets 'appmapper.png'), (Get-IconPng 256))
$frames = @(foreach ($size in @(16, 20, 24, 32, 40, 48, 64, 128, 256)) {
    [pscustomobject]@{ Size = $size; Bytes = (Get-IconPng $size) }
})
$stream = [IO.File]::Create((Join-Path $windowsAssets 'appmapper.ico'))
$writer = [IO.BinaryWriter]::new($stream)
try {
    $writer.Write([uint16]0)
    $writer.Write([uint16]1)
    $writer.Write([uint16]$frames.Count)
    $offset = 6 + 16 * $frames.Count
    foreach ($frame in $frames) {
        $dimension = if ($frame.Size -eq 256) { 0 } else { $frame.Size }
        $writer.Write([byte]$dimension)
        $writer.Write([byte]$dimension)
        $writer.Write([byte]0)
        $writer.Write([byte]0)
        $writer.Write([uint16]1)
        $writer.Write([uint16]32)
        $writer.Write([uint32]$frame.Bytes.Length)
        $writer.Write([uint32]$offset)
        $offset += $frame.Bytes.Length
    }
    foreach ($frame in $frames) { $writer.Write([byte[]]$frame.Bytes) }
} finally { $writer.Dispose() }
Write-Output 'Generated Android vectors/adaptive icons and Windows PNG/ICO (9 sizes).'
